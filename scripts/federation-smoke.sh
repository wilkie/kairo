#!/usr/bin/env bash
#
# Two-node federation smoke check (`specs/PHASE_2_FEDERATION.md`
# slice 6): build an origin node whose object has a real Git-backed
# revision, serve it with `kairo-federation-http`, pull it into a
# second store through a pinned config entry, and check the second
# store end to end:
#
#   1. `kairo fetch` stores the closure and ingests the Git pack;
#   2. `kairo verify object --no-cwd-repo` is VALID from the cache
#      alone (the source repo is not consulted);
#   3. provenance names the origin;
#   4. a second fetch fetches nothing (incremental).
#
# Usage:
#   scripts/federation-smoke.sh [TARGET_STORE]
#
# `TARGET_STORE` defaults to a temp dir. A target that already
# holds a `config.toml` is refused rather than overwritten. On
# success, writes `$TARGET_STORE/federation-ids.json` with the pulled
# object, the origin's URL, and its node actor, which the real-stack
# e2e suite (`frontend/apps/web-client/e2e-real/`) reads.
#
# Environment:
#   KAIRO_BIN_DIR   where `kairo` and `kairo-federation-http` live
#                   (default ./target/debug)
#   OBJECT_FORMAT   Git object format of the origin repo: sha1
#                   (default) or sha256 (`DECISIONS.md` §19)
#   KAIRO_FED_PORT  port the origin serves on (default 7981)
#
# Needs `git` and `curl` on PATH.

set -euo pipefail

BIN_DIR="${KAIRO_BIN_DIR:-./target/debug}"
KAIRO="$BIN_DIR/kairo"
FED_HTTP="$BIN_DIR/kairo-federation-http"
FORMAT="${OBJECT_FORMAT:-sha1}"
PORT="${KAIRO_FED_PORT:-7981}"
PEER="http://127.0.0.1:$PORT"

for bin in "$KAIRO" "$FED_HTTP"; do
    if [[ ! -x "$bin" ]]; then
        echo "error: $bin not found; run \`cargo build --bins\` or set KAIRO_BIN_DIR" >&2
        exit 1
    fi
done
case "$FORMAT" in
    sha1 | sha256) ;;
    *)
        echo "error: OBJECT_FORMAT must be sha1 or sha256, got $FORMAT" >&2
        exit 1
        ;;
esac

WORK="$(mktemp -d)"
ORIGIN="$WORK/origin"
REPO="$WORK/repo"
TARGET="${1:-$WORK/target}"
mkdir -p "$TARGET"
if [[ -e "$TARGET/config.toml" ]]; then
    echo "error: $TARGET/config.toml exists; refusing to overwrite it" >&2
    exit 1
fi

SERVER_PID=""
cleanup() {
    if [[ -n "$SERVER_PID" ]] && kill -0 "$SERVER_PID" 2>/dev/null; then
        kill "$SERVER_PID"
        wait "$SERVER_PID" 2>/dev/null || true
    fi
    rm -rf "$ORIGIN" "$REPO" "$WORK/server.log" "$WORK/target"
    rmdir "$WORK" 2>/dev/null || true
}
trap cleanup EXIT

fail() {
    echo "FAIL: $*" >&2
    if [[ -f "$WORK/server.log" ]]; then
        echo "--- kairo-federation-http log ---" >&2
        cat "$WORK/server.log" >&2
    fi
    exit 1
}

# `<key> = <value>` from CLI output.
extract() {
    grep -oE "^$1 = [A-Za-z0-9]+" | head -1 | awk '{print $3}'
}

origin() { "$KAIRO" --store "$ORIGIN" "$@"; }
target() { "$KAIRO" --store "$TARGET" "$@"; }

echo "==> origin node ($FORMAT) at $ORIGIN"

# A source repo whose one commit carries the manifest the revision
# signs, so verification can bind manifest and content.
mkdir -p "$REPO"
git -C "$REPO" init --quiet --initial-branch=main --object-format="$FORMAT"
git -C "$REPO" config user.name "Kairo Smoke"
git -C "$REPO" config user.email "smoke@kairo.test"
git -C "$REPO" config commit.gpgsign false
cat >"$REPO/kairo.toml" <<'EOF'
[kairo]
schema = 1
kind = "software"
name = "federation-smoke"
summary = "Generated by scripts/federation-smoke.sh"

[content]
kind = "tree"
EOF
git -C "$REPO" add kairo.toml
git -C "$REPO" commit --quiet -m "federation smoke"
COMMIT="$(git -C "$REPO" rev-parse HEAD)"

NODE=$(origin actor create --kind node --generate-attestation-key 2>/dev/null | extract actor)
ALICE=$(origin actor create --kind person --generate-attestation-key 2>/dev/null | extract actor)
OBJECT=$(origin object create --actor "$ALICE" --kind software | extract object)
REVISION=$(origin revision create --actor "$ALICE" --object "$OBJECT" \
    --revision "git:$FORMAT:$COMMIT" --manifest "$REPO/kairo.toml" | extract statement)
origin branch set --actor "$ALICE" --object "$OBJECT" --revision "$REVISION" >/dev/null
origin git fetch --object "$OBJECT" --remote "file://$REPO" >/dev/null
origin federation publish --object "$OBJECT" >/dev/null

echo "  node actor  $NODE"
echo "  object      $OBJECT"
echo "  revision    git:$FORMAT:$COMMIT"

echo "==> serving on $PEER"
"$FED_HTTP" --store "$ORIGIN" --node-actor "$NODE" --bind "127.0.0.1:$PORT" \
    >"$WORK/server.log" 2>&1 &
SERVER_PID=$!
for _ in $(seq 1 100); do
    if curl -fsS "$PEER/.well-known/kairo-node" >/dev/null 2>&1; then
        break
    fi
    kill -0 "$SERVER_PID" 2>/dev/null || fail "kairo-federation-http exited"
    sleep 0.1
done
curl -fsS "$PEER/.well-known/kairo-node" >/dev/null || fail "server never answered"

echo "==> pulling into $TARGET"
cat >"$TARGET/config.toml" <<EOF
# Written by scripts/federation-smoke.sh.
[[federation.peers]]
url = "$PEER"
node_actor = "$NODE"
EOF
target config validate >/dev/null || fail "generated config does not validate"

FETCHED="$(target fetch --object "$OBJECT" --from "$PEER")" || fail "fetch failed"
echo "$FETCHED" | sed 's/^/  /'
grep -q "^peer_actor = $NODE (pinned; " <<<"$FETCHED" || fail "peer was not pinned"
grep -q "^git = ingested (1 commits)$" <<<"$FETCHED" || fail "Git pack not ingested"

echo "==> verifying from the cache alone"
VERIFIED="$(target verify object --object "$OBJECT" --name head --no-cwd-repo --no-as)" \
    || fail "verify object failed:
$VERIFIED"
grep -q "^verify object: VALID" <<<"$VERIFIED" || fail "not VALID:
$VERIFIED"
grep -q "commit lookup: cache (object $OBJECT)" <<<"$VERIFIED" \
    || fail "commit not resolved from the cache:
$VERIFIED"
echo "  VALID (commit lookup: cache)"

echo "==> provenance and re-fetch"
target federation provenance --ref "object:$OBJECT" | grep -q "peer_url=$PEER " \
    || fail "provenance does not name $PEER"
AGAIN="$(target fetch --object "$OBJECT" --from "$PEER")" || fail "re-fetch failed"
grep -q "^fetched = 0$" <<<"$AGAIN" || fail "re-fetch was not incremental:
$AGAIN"
grep -q "^git = already held" <<<"$AGAIN" || fail "re-fetch re-ingested Git:
$AGAIN"

cat >"$TARGET/federation-ids.json" <<EOF
{
  "object": "$OBJECT",
  "revision": "$REVISION",
  "peerUrl": "$PEER",
  "nodeActor": "$NODE",
  "objectFormat": "$FORMAT"
}
EOF

echo
echo "==> federation smoke passed ($FORMAT)"
